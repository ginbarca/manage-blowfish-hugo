#!/usr/bin/env node

import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(scriptDir, "..");
const lockPath = path.join(root, "upstream.lock.json");
const reportPath = path.join(root, "docs", "UPSTREAM_STATUS.md");
const mode = process.argv.includes("--check") ? "check" : "write";

const sources = {
  blowfish: {
    label: "Blowfish",
    releaseRepository: "nunocoracao/blowfish",
    documentationRepository: "nunocoracao/blowfish",
    documentationPath: "exampleSite/content/docs",
  },
  hugo: {
    label: "Hugo",
    releaseRepository: "gohugoio/hugo",
    documentationRepository: "gohugoio/hugoDocs",
    documentationPath: "content",
  },
};

function headers() {
  const value = {
    Accept: "application/vnd.github+json",
    "User-Agent": "manage-blowfish-hugo-upstream-sync",
    "X-GitHub-Api-Version": "2022-11-28",
  };
  if (process.env.GITHUB_TOKEN) {
    value.Authorization = `Bearer ${process.env.GITHUB_TOKEN}`;
  }
  return value;
}

async function githubJson(endpoint) {
  const response = await fetch(`https://api.github.com${endpoint}`, {
    headers: headers(),
  });
  if (!response.ok) {
    throw new Error(
      `GitHub API ${response.status} for ${endpoint}: ${await response.text()}`,
    );
  }
  return response.json();
}

async function readRelease(repository) {
  const release = await githubJson(`/repos/${repository}/releases/latest`);
  return {
    repository,
    tag: release.tag_name,
    url: release.html_url,
    publishedAt: release.published_at,
  };
}

async function readDocumentationRevision(repository, documentationPath) {
  const commits = await githubJson(
    `/repos/${repository}/commits?path=${encodeURIComponent(
      documentationPath,
    )}&per_page=1`,
  );
  const commit = commits[0];
  if (!commit) {
    throw new Error(
      `No documentation commit found for ${repository}:${documentationPath}`,
    );
  }
  return {
    repository,
    path: documentationPath,
    sha: commit.sha,
    url: commit.html_url,
    committedAt:
      commit.commit?.committer?.date ?? commit.commit?.author?.date ?? null,
  };
}

function shortSha(value) {
  return value ? value.slice(0, 12) : "Pending first automated check";
}

function markdownLink(label, url) {
  return url ? `[${label}](${url})` : label;
}

function generateReport(lock) {
  const rows = Object.entries(sources).map(([key, source]) => {
    const state = lock.sources[key];
    const release = markdownLink(state.release.tag, state.release.url);
    const documentation = state.documentation.sha
      ? markdownLink(shortSha(state.documentation.sha), state.documentation.url)
      : shortSha(null);
    return `| ${source.label} | ${release} | ${documentation} |`;
  });

  return `# Upstream status

This file is generated by \`scripts/check-upstream.mjs\`.

| Source | Tracked release | Documentation revision |
| --- | --- | --- |
${rows.join("\n")}

The release lock records discovery state. Curated skill references are updated
in the reviewable pull request created by Upstream Sync.
`;
}

async function main() {
  const previous = JSON.parse(fs.readFileSync(lockPath, "utf8"));
  const entries = await Promise.all(
    Object.entries(sources).map(async ([key, source]) => {
      const [release, documentation] = await Promise.all([
        readRelease(source.releaseRepository),
        readDocumentationRevision(
          source.documentationRepository,
          source.documentationPath,
        ),
      ]);
      return [key, { release, documentation }];
    }),
  );

  const next = {
    schema: 1,
    sources: Object.fromEntries(entries),
  };
  const nextLock = `${JSON.stringify(next, null, 2)}\n`;
  const previousLock = `${JSON.stringify(previous, null, 2)}\n`;
  const nextReport = generateReport(next);
  const previousReport = fs.existsSync(reportPath)
    ? fs.readFileSync(reportPath, "utf8")
    : "";
  const changed = nextLock !== previousLock || nextReport !== previousReport;

  for (const [key, source] of Object.entries(sources)) {
    const before = previous.sources?.[key];
    const after = next.sources[key];
    console.log(
      `${source.label}: ${before?.release?.tag ?? "unknown"} -> ${
        after.release.tag
      }, docs ${shortSha(before?.documentation?.sha)} -> ${shortSha(
        after.documentation.sha,
      )}`,
    );
  }

  if (!changed) {
    console.log("Upstream state is unchanged.");
    return;
  }

  if (mode === "check") {
    console.error("Upstream updates are available.");
    process.exitCode = 2;
    return;
  }

  fs.writeFileSync(lockPath, nextLock);
  fs.writeFileSync(reportPath, nextReport);
  console.log("Updated upstream.lock.json and docs/UPSTREAM_STATUS.md.");
}

main().catch((error) => {
  console.error(error instanceof Error ? error.stack : String(error));
  process.exit(1);
});

